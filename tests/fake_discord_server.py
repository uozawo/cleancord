"""Tiny HTTPS stand-in for discord.com used by browser_test.py to check that the extension picks up the session from a Discord tab."""
import http.server, ssl, sys, json
class H(http.server.BaseHTTPRequestHandler):
    def log_message(self, *a): pass
    def do_GET(self):
        if self.path.startswith('/api/'):
            body = json.dumps({'id': '1'}).encode(); ctype = 'application/json'
        else:
            body = b'<html><body>fake discord<script>setTimeout(()=>fetch("/api/v9/users/@me",{headers:{Authorization:"captured-token-123","X-Super-Properties":"abc"}}),300)</script></body></html>'; ctype = 'text/html'
        self.send_response(200); self.send_header('content-type', ctype); self.send_header('content-length', str(len(body))); self.end_headers(); self.wfile.write(body)
# usage: fake_discord_server.py PORT CERT_DIR  (cert.pem/key.pem are generated by browser_test.py)
port = int(sys.argv[1]) if len(sys.argv) > 1 else 8443
cert_dir = sys.argv[2] if len(sys.argv) > 2 else '.'
srv = http.server.ThreadingHTTPServer(('127.0.0.1', port), H)
ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER); ctx.load_cert_chain(f'{cert_dir}/cert.pem', f'{cert_dir}/key.pem')
srv.socket = ctx.wrap_socket(srv.socket, server_side=True)
srv.serve_forever()
